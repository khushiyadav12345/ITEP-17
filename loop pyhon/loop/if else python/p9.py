# 9️⃣ Largest Value Using Expressions

# Write a JavaScript program using the conditional operator to compare two arithmetic expressions and display the greater result.

expression1 = (2 + 2) * 2
expression2 = (100 - 5) / 2
if expression1 > expression2:
    result = f"The greater result is from expression1: {expression1}"
else:
    result = f"The greater result is from expression2: {expression2}"
print(result)